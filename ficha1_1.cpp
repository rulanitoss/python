#include <iostream>

using namespace std;

int main ()
{
    int numero;
    cout << "Me de um numero:";
    cin >> numero;

    if (numero < 0)
    {
        cout <<"Numero Negativo";
    }
    else if (numero == 0)
    {
        cout << "Numero Neutro";
    }
    else if (numero > 0;numero <100)
    {
        cout << "Numero Positivo Pequeno";
    }
    else
        cout << "Numero Enorme";


return 0;
}
